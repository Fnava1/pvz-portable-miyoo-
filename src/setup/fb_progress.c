static inline void set_pixel(int x, int y, uint8_t r, uint8_t g, uint8_t b) {
    if (x < 0 || x >= s_fb_width || y < 0 || y >= s_fb_height || !s_fb_ptr) {
        return;
    }

    if (s_fb_bpp == 16) {
        uint16_t *dst = (uint16_t *)(s_fb_ptr + y * s_fb_line_len + x * 2);
        *dst = (uint16_t)(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3));
    } else if (s_fb_bpp == 32) {
        uint32_t *dst = (uint32_t *)(s_fb_ptr + y * s_fb_line_len + x * 4);
        *dst = (0xFF000000u) | ((uint32_t)r << 16) | ((uint32_t)g << 8) | (uint32_t)b;
    }
}

static void fill_rect(int x, int y, int w, int h, uint8_t r, uint8_t g, uint8_t b) {
    for (int j = y; j < y + h; ++j) {
        for (int i = x; i < x + w; ++i) {
            set_pixel(i, j, r, g, b);
        }
    }
}

static void draw_char(int x, int y, char c, int scale, uint8_t r, uint8_t g, uint8_t b) {
    if (c < 32 || c > 126) c = ' ';
    const uint8_t *glyph = s_font8x8[c - 32];
    for (int row = 0; row < 8; ++row) {
        uint8_t line = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if (line & (0x80 >> col)) {
                if (scale == 1) {
                    set_pixel(x + col, y + row, r, g, b);
                } else {
                    for (int dy = 0; dy < scale; ++dy) {
                        for (int dx = 0; dx < scale; ++dx) {
                            set_pixel(x + col * scale + dx, y + row * scale + dy, r, g, b);
                        }
                    }
                }
            }
        }
    }
}

static void draw_string(int x, int y, const char *str, int scale, uint8_t r, uint8_t g, uint8_t b) {
    if (!str) return;
    int cur_x = x;
    while (*str) {
        draw_char(cur_x, y, *str, scale, r, g, b);
        cur_x += 8 * scale;
        str++;
    }
}

int fb_progress_init(void) {
    s_fb_fd = open("/dev/fb0", O_RDWR);
    if (s_fb_fd < 0) {
        s_fb_active = 0;
        printf("[SETUP] Notice: /dev/fb0 unavailable (using console output mode)\n");
        return 0;
    }

    struct fb_var_screeninfo vinfo;
    struct fb_fix_screeninfo finfo;

    if (ioctl(s_fb_fd, FBIOGET_VSCREENINFO, &vinfo) < 0 ||
        ioctl(s_fb_fd, FBIOGET_FSCREENINFO, &finfo) < 0) {
        close(s_fb_fd);
        s_fb_fd = -1;
        s_fb_active = 0;
        printf("[SETUP] Notice: Unable to query framebuffer info (using console output)\n");
        return 0;
    }

    s_fb_width = vinfo.xres;
    s_fb_height = vinfo.yres;
    s_fb_bpp = vinfo.bits_per_pixel;
    s_fb_line_len = finfo.line_length;
    s_fb_size = finfo.smem_len;

    if (s_fb_bpp != 16 && s_fb_bpp != 32) {
        close(s_fb_fd);
        s_fb_fd = -1;
        s_fb_active = 0;
        printf("[SETUP] Unsupported framebuffer depth: %d bpp (using console output)\n", s_fb_bpp);
        return 0;
    }

    s_fb_ptr = (uint8_t *)mmap(NULL, s_fb_size, PROT_READ | PROT_WRITE, MAP_SHARED, s_fb_fd, 0);
    if (s_fb_ptr == MAP_FAILED) {
        s_fb_ptr = NULL;
        close(s_fb_fd);
        s_fb_fd = -1;
        s_fb_active = 0;
        printf("[SETUP] Failed to mmap /dev/fb0 (using console output)\n");
        return 0;
    }

    s_fb_active = 1;

    // Clear screen to deep slate
    fill_rect(0, 0, s_fb_width, s_fb_height, 20, 26, 32);

    // Initial title rendering
    int title_x = (s_fb_width - (18 * 8 * 2)) / 2;
    if (title_x < 10) title_x = 10;
    draw_string(title_x, 150, "PLANTS VS. ZOMBIES", 2, 230, 230, 230);

    const char *sub = "Optimizando Plants vs. Zombies para Miyoo Mini...";
    int sub_x = (s_fb_width - ((int)strlen(sub) * 8)) / 2;
    if (sub_x < 10) sub_x = 10;
    draw_string(sub_x, 195, sub, 1, 160, 180, 200);

    return 0;
}

int fb_progress_is_fb_active(void) {
    return s_fb_active;
}

void fb_progress_update(float progress, const char *status_text) {
    int pct = (int)(progress * 100.0f);
    if (pct < 0) pct = 0;
    if (pct > 100) pct = 100;

    if (!s_fb_active) {
        printf("\r[Miyoo Setup %3d%%] %s", pct, status_text ? status_text : "");
        fflush(stdout);
        if (progress >= 1.0f) {
            printf("\n");
        }
        return;
    }

    // Geometry for progress bar
    int bar_w = (int)(s_fb_width * 0.75f);
    if (bar_w > 480) bar_w = 480;
    int bar_h = 24;
    int bar_x = (s_fb_width - bar_w) / 2;
    int bar_y = 240;

    // Outer border
    fill_rect(bar_x - 2, bar_y - 2, bar_w + 4, bar_h + 4, 100, 110, 120);
    // Background
    fill_rect(bar_x, bar_y, bar_w, bar_h, 10, 14, 18);

    // Filled bar (PvZ green)
    int fill_w = (int)((bar_w) * progress);
    if (fill_w > bar_w) fill_w = bar_w;
    if (fill_w > 0) {
        fill_rect(bar_x, bar_y, fill_w, bar_h, 50, 180, 80);
    }

    // Status / file text line (clear line first)
    int text_y = bar_y + bar_h + 16;
    fill_rect(10, text_y, s_fb_width - 20, 16, 20, 26, 32);

    char buf[128];
    snprintf(buf, sizeof(buf), "[%3d%%] %s", pct, status_text ? status_text : "");
    buf[sizeof(buf) - 1] = '\0';
    draw_string(bar_x, text_y, buf, 1, 200, 210, 220);
}

void fb_progress_close(void) {
    if (s_fb_active && s_fb_ptr) {
        // Draw completion banner before closing
        draw_string((s_fb_width - 200) / 2, 320, "INSTALACION COMPLETA!", 1, 80, 240, 100);
        munmap(s_fb_ptr, s_fb_size);
        s_fb_ptr = NULL;
    }
    if (s_fb_fd >= 0) {
        close(s_fb_fd);
        s_fb_fd = -1;
    }
    s_fb_active = 0;
}
